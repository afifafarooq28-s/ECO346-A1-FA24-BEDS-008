import pandas as pd

person = pd.read_csv('/content/pslm_person_subset.csv')
hh = pd.read_csv('/content/pslm_hh_subset.csv')

print(person.shape)
print(hh.shape)

person = person.merge(
    hh[['hhid', 'prov_code', 'urban_rural', 'hhweight']],
    on='hhid',
    how='left'
)

punjab_rural = person[
    (person['prov_code'] == 2) &
    (person['urban_rural'] == 1)
].copy()

print(punjab_rural.shape)

literacy = punjab_rural[
    (punjab_rural['age'] >= 10) &
    (punjab_rural['age'] <= 64) &
    (punjab_rural['literate'].notna())
].copy()

literacy['age_band'] = (literacy['age'] // 5) * 5

print(literacy.shape)
print(literacy[['age', 'sex', 'literate', 'hhweight', 'age_band']].head())

literacy['sex_label'] = literacy['sex'].map({1: 'Men', 2: 'Women'})

table = literacy.groupby(['age_band', 'sex_label']).apply(
    lambda g: pd.Series({
        'n': len(g),
        'literacy_rate': (
            (g['literate'] * g['hhweight']).sum()
            / g['hhweight'].sum()
        ) * 100
    }),
    include_groups=False
).reset_index()

table['literacy_rate'] = table['literacy_rate'].round(1)

print(table.to_string(index=False))

import matplotlib.pyplot as plt

for sex in ['Men', 'Women']:
    d = table[table['sex_label'] == sex]
    plt.plot(
        d['age_band'] + 2,
        d['literacy_rate'],
        marker='o',
        label=sex
    )

plt.xlabel('Age band')
plt.ylabel('Weighted literacy rate (%)')
plt.title('Literacy rates by age and sex in rural Punjab')
plt.xticks(range(12, 63, 5))
plt.ylim(0, 100)
plt.legend()
plt.savefig('q5_literacy.svg', format='svg', bbox_inches='tight')
plt.show()